#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const pkg=JSON.parse(read('package.json'));
for(const name of ['core','ios','android'])assert.equal(pkg.dependencies['@capacitor/'+name],'8.5.3');
assert.equal(pkg.devDependencies['@capacitor/cli'],'8.5.3');
for(const name of ['@capacitor-community/admob','@capacitor-community/keep-awake','@capacitor/local-notifications'])assert.match(pkg.dependencies[name],/^8\./);
const config=JSON.parse(read('capacitor.config.json'));
assert.equal(config.appId,'com.lipastudios.entrenoapp');
assert.equal(config.plugins.SystemBars.insetsHandling,'native');
assert.doesNotMatch(read('app.html').match(/<meta name="viewport"[^>]+>/)[0],/viewport-fit=cover/);
const variables=read('android/variables.gradle');
assert.match(variables,/minSdkVersion\s*=\s*24\b/);
assert.match(variables,/compileSdkVersion\s*=\s*36\b/);
assert.match(variables,/targetSdkVersion\s*=\s*36\b/);
assert.match(read('android/build.gradle'),/com\.android\.tools\.build:gradle:8\.13\.2/);
assert.match(read('android/gradle/wrapper/gradle-wrapper.properties'),/gradle-8\.14\.3-all\.zip/);
assert.match(read('android/gradle/wrapper/gradle-wrapper.properties'),/distributionSha256Sum=[a-f0-9]{64}/);
assert.match(read('android/app/src/main/java/com/lipastudios/entrenoapp/MainActivity.java'),/EdgeToEdge\.enable\(this\)/);
assert.match(read('android/app/src/main/AndroidManifest.xml'),/navigation\|density/);
const project=read('ios/App/App.xcodeproj/project.pbxproj');
assert.equal((project.match(/SceneDelegate.swift in Sources/g)||[]).length,2);
assert.equal((project.match(/CURRENT_PROJECT_VERSION = 123;/g)||[]).length,2);
assert.doesNotMatch(project,/IPHONEOS_DEPLOYMENT_TARGET = (?:1[0-4])\./);
assert.match(read('ios/App/App/Info.plist'),/UIApplicationSceneManifest/);
assert.match(read('ios/App/App/Info.plist'),/\$\(PRODUCT_MODULE_NAME\)\.SceneDelegate/);
assert.match(read('ios/App/App/SceneDelegate.swift'),/SceneDelegateProxy\.shared\.scene\(scene, willConnectTo:/);
assert.match(read('ios/App/App/SceneDelegate.swift'),/SceneDelegateProxy\.shared\.scene\(scene, openURLContexts:/);
assert.match(read('ios/App/App/SceneDelegate.swift'),/SceneDelegateProxy\.shared\.scene\(scene, continue:/);
assert.match(read('ios/App/App/AppDelegate.swift'),/config.delegateClass = SceneDelegate.self/);
assert.doesNotMatch(read('ios/App/Podfile'),/system\('node', patch\)/);
assert.match(read('app.html'),/data-ad-privacy hidden onclick="showAdPrivacyOptions\(\)"/);
console.log('PASS: Capacitor 8 pins, API36/min24, SystemBars insets, Gradle checksum, iOS15/123 UIScene and privacy entry point.');
